'use strict';
const assert=require('assert');
require('../app/markdown/vendor/config-parsers.js');
require('../app/markdown/config-parser.js');
const api=global.FolderwingConfig;
const value=(n,s)=>s.slice(n.start,n.end);
const get=(n,key)=>n.children.find(x=>x.key===key);
const yaml='defaults: &defaults\n  big: 9223372036854775807\n  name: "text"\ncopy: *defaults\n---\n? [one, two]\n: 0x10\ncustom: !widget hello\n';
const docs=api.parse(yaml,'yaml',false);
assert.strictEqual(docs.length,2);
const defaults=get(docs[0].root,'defaults'),big=get(defaults,'big'),alias=get(docs[0].root,'copy');
assert.strictEqual(value(big,yaml),'9223372036854775807');
assert.strictEqual(defaults.badge,'&defaults');
assert.strictEqual(defaults.noCopyValue,true);
assert.strictEqual(alias.type,'alias');assert.strictEqual(alias.aliasTarget,defaults);
assert.strictEqual(value(alias,yaml),'*defaults');
assert.strictEqual(docs[1].root.children[0].path,null);
assert(docs[1].warnings.some(x=>x.includes('!widget')));
assert.strictEqual(get(docs[1].root,'custom').badge,'!widget');
assert.strictEqual(get(docs[1].root,'custom').noCopyValue,true);
const tagged=api.parse('value: !!str 0123\n','yaml',false)[0];
assert.strictEqual(get(tagged.root,'value').noCopyValue,true);
const cycle=api.parse('self: &a { ref: *a }\n','yaml',false)[0];
const self=get(cycle.root,'self');assert.strictEqual(get(self,'ref').aliasTarget,self);
const mixed=api.parse('a: [\n---\nok: yes\n','yaml',false);
assert(mixed[0].error);assert(!mixed[1].error);assert.strictEqual(value(get(mixed[1].root,'ok'),mixed[1].source),'yes');
const empty=api.parse('','yaml',false)[0];assert.strictEqual(empty.root.display,'null');
const missing=api.parse('empty:\n','yaml',false)[0];assert.strictEqual(get(missing.root,'empty').display,'null');
const toml='title="hello"\nbig=9223372036854775807\nwhen=1979-05-27T07:32:00Z\n[owner]\nname="Rose"\nitems=[1, { label="x" }]\n[[fruit]]\nname="apple"\n[[fruit]]\nname="banana"\n';
const result=api.parse(toml,'toml',false)[0],root=result.root;
assert.strictEqual(value(get(root,'big'),toml),'9223372036854775807');
assert.strictEqual(value(get(root,'when'),toml),'1979-05-27T07:32:00Z');
assert.strictEqual(value(get(get(root,'owner'),'name'),toml),'"Rose"');
assert.strictEqual(value(get(get(root,'owner'),'items').children[1].children[0],toml),'"x"');
assert.strictEqual(value(get(get(root,'fruit').children[1],'name'),toml),'"banana"');
assert.strictEqual(get(root,'owner').noCopyValue,true);
const nested='[[fruit]]\nname="apple"\n[fruit.physical]\ncolor="red"\n[[fruit]]\nname="banana"\n[[fruit.variety]]\nname="plantain"\n';
const nestedRoot=api.parse(nested,'toml',false)[0].root,fruit=get(nestedRoot,'fruit');
assert.strictEqual(value(get(get(fruit.children[0],'physical'),'color'),nested),'"red"');
assert.strictEqual(value(get(get(fruit.children[1],'variety').children[0],'name'),nested),'"plantain"');
const strange=api.parse('__proto__ = "kept"\n"a.b".c = 1\n','toml',false)[0];
assert.strictEqual(value(get(strange.root,'__proto__'),strange.source),'"kept"');
assert.strictEqual(value(get(get(strange.root,'a.b'),'c'),strange.source),'1');
assert.throws(()=>api.parse('x=2023-02-30\n','toml',false));
assert.throws(()=>api.parse('x=1\nx=2\n','toml',false));
assert.throws(()=>api.parse('x=1','toml',true),/size limit/);
console.log('YAML and TOML parser checks passed.');
