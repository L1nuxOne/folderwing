'use strict';
const assert=require('assert');
require('../app/markdown/vendor/config-parsers.js');
require('../app/markdown/config-parser.js');
const parse=global.FolderwingConfig.parse;
const source='; comment\r\nroot = 007\r\n[Repeated]\r\nName = first\r\nunknown directive\r\nurl=https://example.test/#fragment;value\r\n[repeated]\r\nname=second\r\n[Unique]\r\nKey=one\r\nkey=two\r\nempty=\r\nliteral=${OTHER}=yes\r\ncolon: unparsed\r\n[bad] trailing\r\n';
const result=parse(source,'ini',false)[0],root=result.root;
const raw=n=>source.slice(n.start,n.end);
assert.deepStrictEqual(root.children.map(n=>n.key),['root','Repeated','repeated','Unique']);
assert.strictEqual(raw(root.children[0]),' 007');
const first=root.children[1],second=root.children[2],unique=root.children[3];
assert.strictEqual(first.path,null);assert.strictEqual(second.path,null);
assert(first.children.every(n=>n.path===null));assert(second.children.every(n=>n.path===null));
assert.deepStrictEqual(first.children.map(n=>n.key),['Name','Line 5','url']);
assert.strictEqual(first.children[1].badge,'unparsed');assert.strictEqual(raw(first.children[1]),'unknown directive');
assert.strictEqual(raw(first.children[2]),'https://example.test/#fragment;value');
assert.deepStrictEqual(unique.children.map(n=>n.key),['Key','key','empty','literal','Line 14','Line 15']);
assert.strictEqual(unique.children[0].path,null);assert.strictEqual(unique.children[1].path,null);
assert.strictEqual(raw(unique.children[2]),'');assert.strictEqual(raw(unique.children[3]),'${OTHER}=yes');
assert.strictEqual(unique.children[3].path,'$["Unique"]["literal"]');
assert(result.warnings[0].includes('3 unparsed lines'));
assert.deepStrictEqual(parse('','ini',false)[0].root.children,[]);
assert.throws(()=>parse('a=1','ini',true),/size limit/);
console.log('INI parser checks passed.');
